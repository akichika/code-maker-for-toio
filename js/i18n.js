/* ── Public API ─────────────────────────────────────────────────────────────── */

const _SUPPORTED = Object.keys(LANGS);
let _current = localStorage.getItem('lang') || 'ja';
if (!_SUPPORTED.includes(_current)) _current = 'ja';

function t(key) {
  return (LANGS[_current] && LANGS[_current][key]) ||
         (LANGS['ja'] && LANGS['ja'][key]) ||
         key;
}

function currentLang() { return _current; }

function setLang(lang) {
  if (!_SUPPORTED.includes(lang)) return;
  // Allow the app to snapshot workspace state before the reload
  if (typeof window._onBeforeLangReload === 'function') {
    try { window._onBeforeLangReload(); } catch(e) {}
  }
  localStorage.setItem('lang', lang);
  location.reload();
}

window.t            = t;
window.currentLang  = currentLang;
window.setLang      = setLang;
window.LANGS        = LANGS;
